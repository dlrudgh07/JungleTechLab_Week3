#pragma once

#include "Renderer.h"

// 텍스처/UV 테스트용 사각형. 정점 6개(삼각형 2개), 인덱스 버퍼는 쓰지 않는다.
//
// 좌표는 Cube_vertices 의 +X 면을 그대로 가져왔다. 큐브 면은 이미 바깥에서 볼 때
// 앞면(시계 방향)이 되도록 순서가 맞춰져 있어서, CULL_BACK 인 래스터라이저를
// 그대로 통과한다. 정점 순서를 직접 짜면 여기서 자주 틀리고, 틀리면 면이 통째로
// 사라진다. (와이어프레임은 CULL_NONE 이라 그때도 보인다. 원인 가르는 데 쓸 것)
//
// 그래서 이 평면은 로컬 +X 를 바라보는 벽이다. x = +0.5 고정, y/z 가 -0.5 ~ +0.5.
//
// [화면 방향]
// 카메라 기준은 Forward = X, Right = Y, Up = Z (FCamera::GetForwardVector 등).
// 이 면을 바깥(+X 쪽)에서 보면 카메라 Forward 가 -X 이므로
//   화면 위쪽   = +Z
//   화면 오른쪽 = -Y
// 가 된다. y 가 "줄어드는" 쪽이 화면 오른쪽이라는 게 헷갈리는 지점이다.
//
// [UV]
// DirectX 텍스처 공간은 (0,0) 이 좌상단이고 V 가 아래로 증가한다. 위 화면 방향과
// 합치면
//   u = 0.5 - y   (y=+0.5 -> u=0 왼쪽,  y=-0.5 -> u=1 오른쪽)
//   v = 0.5 - z   (z=+0.5 -> v=0 위,    z=-0.5 -> v=1 아래)
//
//        y=+0.5      y=-0.5
//   z=+0.5  (0,0) --- (1,0)
//             |         |
//   z=-0.5  (0,1) --- (1,1)
//
// PS 에서 return float4(uv, 0, 1) 로 확인하면
//   좌상단 검정 / 우상단 빨강 / 좌하단 초록 / 우하단 노랑
// 이 나와야 한다. 좌우가 뒤집혀 보이면 u 식을, 위아래가 뒤집혀 보이면 v 식을
// 의심할 것. 둘은 서로 독립이라 따로 판단할 수 있다.
//
// 정점 색은 전부 흰색이다. 샘플링한 텍스처 색에 곱하거나 섞을 때 색조가 끼어들지
// 않게 하기 위함이다. (큐브처럼 면별 색을 넣으면 텍스처가 그 색으로 물든다)
//
// 삼각형 2개가 코너 2개 - (0,1) 과 (1,0) - 를 공유하는데, 좌표뿐 아니라 UV 도
// 똑같아야 한다. 어긋나면 두 삼각형의 경계인 대각선을 따라 찢어진 자국이 생긴다.
inline FVertexSimple Plane_vertices[6] =
{
	// 삼각형 1
	{ 0.5f,  0.5f, -0.5f,   1.0f, 1.0f, 1.0f, 1.0f,   0.0f, 1.0f }, // 좌하단
	{ 0.5f,  0.5f,  0.5f,   1.0f, 1.0f, 1.0f, 1.0f,   0.0f, 0.0f }, // 좌상단
	{ 0.5f, -0.5f,  0.5f,   1.0f, 1.0f, 1.0f, 1.0f,   1.0f, 0.0f }, // 우상단

	// 삼각형 2
	{ 0.5f,  0.5f, -0.5f,   1.0f, 1.0f, 1.0f, 1.0f,   0.0f, 1.0f }, // 좌하단
	{ 0.5f, -0.5f,  0.5f,   1.0f, 1.0f, 1.0f, 1.0f,   1.0f, 0.0f }, // 우상단
	{ 0.5f, -0.5f, -0.5f,   1.0f, 1.0f, 1.0f, 1.0f,   1.0f, 1.0f }, // 우하단
};
